//! compat: pose checks, mixer, saturation, and the legacy `h3_direct.H3` model.

use h3cs::compat::{check_pose, mix, saturate, LegacyH3Model, PoseError};
use h3cs::types::{LimitReason, Pose, VirtualPos};

fn pose(pitch: f64, roll: f64, yaw: f64) -> Pose {
    Pose { pitch, roll, yaw }
}

// ---------------------------------------------------------------- check_pose

#[test]
fn check_pose_passes_in_range_values_untouched() {
    let c = check_pose(pose(0.3, -0.2, 1.0), 0.2, 0.35, true).unwrap();
    assert_eq!(c.pose, pose(0.3, -0.2, 1.0));
    assert_eq!(c.effective_gain, 0.2);
    assert!(c.limits.is_empty());
}

#[test]
fn check_pose_rejects_non_finite_with_field_name() {
    let cases = [
        (pose(f64::NAN, 0.0, 0.0), 0.3, "pitch"),
        (pose(0.0, f64::INFINITY, 0.0), 0.3, "roll"),
        (pose(0.0, 0.0, f64::NEG_INFINITY), 0.3, "yaw"),
        (pose(0.0, 0.0, 0.0), f64::NAN, "gain"),
        (pose(0.0, 0.0, 0.0), f64::INFINITY, "gain"),
    ];
    for (p, g, field) in cases {
        // Non-finite is rejected even in clamp mode.
        for clamp in [true, false] {
            assert_eq!(check_pose(p, g, 0.35, clamp), Err(PoseError::NonFinite(field)));
        }
    }
}

#[test]
fn check_pose_clamps_out_of_range_and_reports_once() {
    let c = check_pose(pose(1.5, -2.0, 0.5), 0.3, 0.35, true).unwrap();
    assert_eq!(c.pose, pose(1.0, -1.0, 0.5));
    assert_eq!(c.limits, vec![LimitReason::PoseClamped]);
}

#[test]
fn check_pose_rejects_out_of_range_when_clamping_disabled() {
    assert_eq!(check_pose(pose(0.0, 1.0001, 0.0), 0.3, 0.35, false), Err(PoseError::OutOfRange("roll")));
    assert_eq!(check_pose(pose(-1.1, 0.0, 0.0), 0.3, 0.35, false), Err(PoseError::OutOfRange("pitch")));
    // Boundaries are inclusive.
    assert!(check_pose(pose(-1.0, 1.0, -1.0), 0.3, 0.35, false).is_ok());
}

#[test]
fn check_pose_gain_limits() {
    let c = check_pose(Pose::ZERO, 0.6, 0.35, true).unwrap();
    assert_eq!(c.effective_gain, 0.35);
    assert_eq!(c.limits, vec![LimitReason::GainLimited]);

    let c = check_pose(Pose::ZERO, -0.1, 0.35, true).unwrap();
    assert_eq!(c.effective_gain, 0.0);
    assert_eq!(c.limits, vec![LimitReason::GainNegative]);

    let c = check_pose(Pose::ZERO, 0.35, 0.35, true).unwrap();
    assert_eq!(c.effective_gain, 0.35);
    assert!(c.limits.is_empty());

    let c = check_pose(pose(2.0, 0.0, 0.0), 0.9, 0.35, true).unwrap();
    assert_eq!(c.limits, vec![LimitReason::PoseClamped, LimitReason::GainLimited]);
}

#[test]
fn check_pose_bad_max_gain_does_not_panic() {
    let c = check_pose(Pose::ZERO, 0.3, f64::NAN, true).unwrap();
    assert_eq!(c.effective_gain, 0.0);
    let c = check_pose(Pose::ZERO, 0.3, -1.0, true).unwrap();
    assert_eq!(c.effective_gain, 0.0);
}

// ----------------------------------------------------------------------- mix

fn mixed(p: Pose, g: f64) -> [f64; 3] {
    mix(p, g).map(|v| v.0)
}

#[test]
fn mix_matches_plan_table_signs() {
    // architecture §12, gain 0.35 → g = 178.85. Signs are the h3_direct contract.
    let g = 0.35 * 511.0;
    assert_eq!(mixed(pose(1.0, 0.0, 0.0), 0.35), [512.0 + g, 512.0 - g, 512.0]);
    assert_eq!(mixed(pose(0.0, 1.0, 0.0), 0.35), [512.0 + g, 512.0 + g, 512.0]);
    assert_eq!(mixed(pose(0.0, 0.0, 1.0), 0.35), [512.0, 512.0, 512.0 + g]);
    assert_eq!(mixed(pose(-1.0, 0.0, 0.0), 0.35), [512.0 - g, 512.0 + g, 512.0]);
    assert_eq!(mixed(Pose::ZERO, 0.35), [512.0; 3]);
}

#[test]
fn mix_is_unclamped() {
    assert_eq!(mixed(pose(1.0, 1.0, 1.0), 1.0), [1534.0, 512.0, 1023.0]);
    assert_eq!(mixed(pose(1.0, -1.0, -1.0), 1.0), [512.0, -510.0, 1.0]);
}

// ------------------------------------------------------------------ saturate

#[test]
fn saturate_reports_only_when_changed() {
    let v = [VirtualPos(0.0), VirtualPos(512.0), VirtualPos(1023.0)];
    assert_eq!(saturate(v, 0.0, 1023.0), (v, false));

    let (out, sat) = saturate([VirtualPos(1534.0), VirtualPos(-510.0), VirtualPos(700.0)], 0.0, 1023.0);
    assert!(sat);
    assert_eq!(out, [VirtualPos(1023.0), VirtualPos(0.0), VirtualPos(700.0)]);

    let (out, sat) = saturate([VirtualPos(50.0), VirtualPos(512.0), VirtualPos(990.0)], 100.0, 900.0);
    assert!(sat);
    assert_eq!(out, [VirtualPos(100.0), VirtualPos(512.0), VirtualPos(900.0)]);
}

#[test]
fn saturate_nan_and_inverted_bounds_do_not_panic() {
    let (out, sat) = saturate([VirtualPos(f64::NAN), VirtualPos(1.0), VirtualPos(2.0)], 0.0, 1023.0);
    assert!(sat);
    assert_eq!(out[0], VirtualPos(0.0));
    let _ = saturate([VirtualPos(5.0); 3], 10.0, 0.0);
}

// ------------------------------------------------------------- legacy model

#[test]
fn legacy_send_value_truncates_toward_zero_then_clamps() {
    assert_eq!(LegacyH3Model::send_value(690.85), 690);
    assert_eq!(LegacyH3Model::send_value(1023.9), 1023);
    assert_eq!(LegacyH3Model::send_value(1534.0), 1023);
    assert_eq!(LegacyH3Model::send_value(-0.5), 0);
    assert_eq!(LegacyH3Model::send_value(-510.0), 0);
    assert_eq!(LegacyH3Model::send_value(0.999), 0);
    assert_eq!(LegacyH3Model::send_value(f64::NAN), 0);
    assert_eq!(LegacyH3Model::send_value(f64::INFINITY), 1023);
}

#[test]
fn legacy_wire_bytes_layout() {
    assert_eq!(
        LegacyH3Model::wire_bytes([690, 333, 512]),
        vec![b'[', b'A', 0x02, 0xB2, b']', b'[', b'B', 0x01, 0x4D, b']', b'[', b'C', 0x02, 0x00, b']']
    );
}

#[test]
fn legacy_cur_keeps_unclipped_value_during_saturation() {
    let mut m = LegacyH3Model::new(1.0, 40.0);
    for _ in 0..30 {
        m.move_(pose(1.0, 1.0, 0.0));
    }
    assert_eq!(m.cur[0], 1534.0);
    // Returning toward centre: the wire stays pinned at 1023 until cur drops below 1024.
    let sent = m.move_(Pose::ZERO);
    assert_eq!(sent[0], 1023);
    assert_eq!(m.cur[0], 1494.0);
}

// -------------------------------------------------- recorded Python fixtures
//
// Ground truth recorded by running the real legacy driver
// h3game/h3_direct.py (git blob SHA 06bc7f0bdda2c5ebff5f9d323074b582629582a0,
// TakuroFukamizu/20261004_shi3z_hackathon) under CPython 3.14 with a fake
// `serial` module (captures write()) and `time.sleep` stubbed out. A subclass
// of `H3` recorded, after every `set_motors` call, the bytes written and
// `repr(self.cur)`. The 30 centre sends made by `H3.__init__` were discarded
// (they leave cur at 512). `wire` is the hex of the 15 bytes written per send;
// `v` is those bytes decoded; `cur` is Python's float state (repr round-trips
// exactly, so equality below is bit-exact). Op::Move = H3.move(pitch, roll, yaw),
// Op::Set = H3.set_motors(m1, m2, m3), Op::Center = H3.center() (30 sends).
// Pose inputs for the sine sweep were computed in Python and are embedded as
// literals so libm differences cannot leak in.

#[derive(Debug, Clone, Copy)]
enum Op {
    Move(f64, f64, f64),
    Set(f64, f64, f64),
    Center,
}

struct S {
    v: [u16; 3],
    cur: [f64; 3],
    wire: &'static str,
}

struct Scenario {
    name: &'static str,
    gain: f64,
    max_step: f64,
    ops: &'static [(Op, &'static [S])],
}

fn unhex(s: &str) -> Vec<u8> {
    (0..s.len()).step_by(2).map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap()).collect()
}

fn run_scenario(sc: &Scenario) {
    let mut m = LegacyH3Model::new(sc.gain, sc.max_step);
    for (oi, (op, expected)) in sc.ops.iter().enumerate() {
        let got: Vec<([u16; 3], [f64; 3])> = match *op {
            Op::Move(p, r, y) => {
                let v = m.move_(pose(p, r, y));
                vec![(v, m.cur)]
            }
            Op::Set(a, b, c) => {
                let v = m.set_motors([a, b, c]);
                vec![(v, m.cur)]
            }
            Op::Center => {
                let mut out = Vec::new();
                for _ in 0..30 {
                    let v = m.set_motors([512.0; 3]);
                    out.push((v, m.cur));
                }
                out
            }
        };
        assert_eq!(got.len(), expected.len(), "{} op {oi}: send count", sc.name);
        for (si, ((v, cur), e)) in got.iter().zip(expected.iter()).enumerate() {
            let at = format!("{} op {oi} ({op:?}) send {si}", sc.name);
            assert_eq!(*v, e.v, "{at}: wire values");
            assert_eq!(cur.map(f64::to_bits), e.cur.map(f64::to_bits), "{at}: cur {cur:?} vs {:?}", e.cur);
            assert_eq!(LegacyH3Model::wire_bytes(*v), unhex(e.wire), "{at}: wire bytes");
        }
    }
}

#[test]
fn legacy_model_matches_python_recordings() {
    for sc in FIXTURES {
        run_scenario(sc);
    }
}

#[test]
fn legacy_center_method_matches_recorded_center() {
    // The saturate_then_center fixture ends with H3.center(); replay it through `center()`.
    let sc = FIXTURES.iter().find(|s| s.name == "saturate_then_center").unwrap();
    let mut m = LegacyH3Model::new(sc.gain, sc.max_step);
    let (last, rest) = sc.ops.split_last().unwrap();
    for (op, _) in rest {
        if let Op::Move(p, r, y) = *op {
            m.move_(pose(p, r, y));
        }
    }
    assert!(matches!(last.0, Op::Center));
    let sends = m.center(30);
    let expected: Vec<[u16; 3]> = last.1.iter().map(|s| s.v).collect();
    assert_eq!(sends, expected);
    assert_eq!(m.cur, [512.0; 3]);
}

